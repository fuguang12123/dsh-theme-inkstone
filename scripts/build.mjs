import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { PLUGIN_ID, THEME_TOKENS } from '../src/tokens.mjs';
import { activateTheme } from '../src/activate.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const css = (await readFile(join(root, 'src/theme.css'), 'utf8')).replace(/\r\n/g, '\n');
const activateSource = activateTheme.toString().replace(/\r\n/g, '\n');
const bundle = `// Generated by scripts/build.mjs; edit src/ instead.\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(PLUGIN_ID)},\n  factory: () => {\n    const tokens = ${JSON.stringify(THEME_TOKENS)};\n    const css = ${JSON.stringify(css)};\n    const activate = ${activateSource};\n    return { name: 'inkstone-theme', inject: ['theme'], apply(ctx) { activate(ctx, tokens, css); } };\n  }\n});\n`;
await mkdir(join(root, 'dist'), { recursive: true });
await writeFile(join(root, 'dist/client.js'), bundle, 'utf8');
await writeFile(join(root, 'dist/index.js'), (await readFile(join(root, 'src/index.mjs'), 'utf8')).replace(/\r\n/g, '\n'), 'utf8');
console.log(`Built ${PLUGIN_ID}: ${Buffer.byteLength(bundle)} bytes; no runtime dependencies.`);
